#!/bin/bash
# Runs the test suites, after ./scripts/build.sh. With no arguments it runs every suite; with
# names, only those. CI runs one suite per job.
#
#   unit         the library's unit specs, and its type check
#   express      test-app-express's end-to-end specs, on @nestjs/platform-express
#   fastify      the same specs on @nestjs/platform-fastify
#   node         the same specs on @nestjs/platform-node
#   react-query  the generated React Query client, against the built test-app-express
#   example      examples/file-based-routing, a workspace of its own (installed separately), and
#                the client its API writes
#   journey      a new monorepo taken through a developer's first day, with both dev servers up
set -e
__dirname=$(realpath "$(dirname "$0")")
root=$(realpath "$__dirname/..")

ALL_SUITES=(unit express fastify node react-query example journey)

# `test-app-express` is the canonical app: it owns every endpoint fixture and spec. The other
# adapter apps receive them by rsync, keeping only their own adapter-specific `create-app.ts`.
# `--delete` keeps the mirrors exact. Without it rsync only ever adds, so a file deleted or
# renamed in the canonical app lingers in the other apps and fails their `tscheck` long after the
# change that orphaned it.
mirror_express() {
  local app="$root/packages/test/test-app-$1"
  rsync -ar --delete "$root/packages/test/test-app-express/src/" "$app/src/" --exclude=.gitkeep
  rsync -ar --delete "$root/packages/test/test-app-express/test/" "$app/test/" --exclude=create-app.ts
}

# An app's clients, generated from scratch, then its type check, which covers them.
codegen_and_check() {
  rm -rf "$root/packages/test/test-app-$1/generated"
  pnpm --filter "test-app-$1" run codegen
  pnpm --filter "test-app-$1" run tscheck
}

# Vitest's options for a suite whose tests count toward the repository's number of tests, which
# the docs' home page shows: a JSON report beside the usual output, which `record_count` reads.
REPORTS=$(mktemp -d)
report() {
  echo --reporter=default --reporter=json "--outputFile.json=$REPORTS/$1.json"
}
record_count() {
  node "$root/scripts/record-test-count.ts" "$1" "$REPORTS/$1.json"
}

# The example's API writes its web app's client with a `codegen` script, which runs the package's
# command by the name it installs. Run again, it must leave the client as it is: compared with a
# copy taken before, so a file it adds or removes counts as well.
example_client_is_current() {
  local example="$root/examples/file-based-routing"
  local generated="$example/packages/client/src/generated"
  local before
  before=$(mktemp -d)
  cp -R "$generated/." "$before"
  pnpm --dir "$example" --filter api run codegen
  if ! diff -r "$before" "$generated"; then
    echo "examples/file-based-routing: \`pnpm --filter api run codegen\` changed the client it has" >&2
    return 1
  fi
}

run_suite() {
  case "$1" in
    unit)
      pnpm --filter nestjs-endpoints run tscheck
      pnpm --filter nestjs-endpoints test run $(report unit)
      record_count unit
      ;;
    express)
      codegen_and_check express
      pnpm --filter test-app-express run test:e2e $(report express)
      record_count express
      ;;
    fastify | node)
      mirror_express "$1"
      codegen_and_check "$1"
      pnpm --filter "test-app-$1" run test:e2e
      ;;
    react-query)
      # The React Query client is generated by test-app-express, and its specs call that app as
      # a consumer runs it: built, on the real ESM runtime. The suite starts and stops the app.
      codegen_and_check express
      pnpm --filter test-react-query-client run tscheck
      pnpm --filter test-app-express run build
      pnpm --filter test-react-query-client test $(report react-query)
      record_count react-query
      ;;
    example)
      example_client_is_current
      pnpm --dir "$root/examples/file-based-routing" run tscheck
      pnpm --dir "$root/examples/file-based-routing" test $(report example)
      record_count example
      ;;
    journey)
      # A project of its own in a temporary folder, which installs the built library and the
      # two apps' packages from the registry, and loads its web app in Playwright's Chromium.
      pnpm --filter test-journey run tscheck
      pnpm --filter test-journey test $(report journey)
      record_count journey
      ;;
    *)
      echo "Unknown suite: $1 (one of: ${ALL_SUITES[*]})" >&2
      exit 1
      ;;
  esac
}

suites=("$@")
if [[ ${#suites[@]} -eq 0 ]]; then
  suites=("${ALL_SUITES[@]}")
fi
for suite in "${suites[@]}"; do
  echo "== $suite"
  run_suite "$suite"
done
