import type { EndpointDescriptor } from '../../descriptors.js';
import { reachableSchemas, rootsOf, type SharedSchemas } from '../../shared-schemas.js';
import { tagDescriptions } from '../hash.js';
import { buildClientObjectExpression } from './buckets.js';
import { operationKinds, type OperationKindOptions } from './operation-kind.js';

/**
 * The wrappers build on the runtime `@kubb/plugin-axios` writes into the
 * generated tree (`.kubb/client.ts`): each `createApiClient` call makes an
 * axios instance and a Kubb client that sends through it
 * (`createClient({ transport: createAxiosTransport(axios) })`), and hands that
 * client to every request function through its per-call `client` option. The
 * few helpers that binding takes are written into the wrapper itself, so the
 * generated output never reaches back into `nestjs-endpoints` at runtime.
 */

const HEADER_AXIOS =
  `/**\n` +
  ` * Generated by nestjs-endpoints — do not edit manually.\n` +
  ` *\n` +
  ` * The Kubb-generated request functions and types live in the sibling\n` +
  ` * directory; this file is the consumer-facing entry point and exposes the\n` +
  ` * namespaced client surface plus the \`ApiClient\` type.\n` +
  ` */\n`;

const HEADER_REACT_QUERY =
  `/**\n` +
  ` * Generated by nestjs-endpoints — do not edit manually.\n` +
  ` *\n` +
  ` * The Kubb-generated request functions, hooks, and types live in the\n` +
  ` * sibling directory; this file is the consumer-facing entry point and\n` +
  ` * exposes the namespaced client surface (request functions, each with its\n` +
  ` * query or mutation options and input schema, + paired hooks) plus\n` +
  ` * \`ApiClient\`, \`useApiClient\`, and \`ApiClientProvider\`.\n` +
  ` */\n`;

/** The axios instance `createApiClient` is given, or makes from axios defaults. */
const AXIOS_INSTANCE_HELPER = `
const _axiosFor = (config?: CreateAxiosDefaults | AxiosInstance): AxiosInstance =>
  // An axios instance is a callable function carrying these instance members;
  // a plain config object is not, so it makes a new instance.
  typeof config === 'function' && 'defaults' in config && 'interceptors' in config
    ? config
    : Axios.create(config as CreateAxiosDefaults | undefined);

/** A Kubb client that sends every request through \`axios\`. */
const _clientFor = (axios: AxiosInstance): ClientInstance =>
  createClient({ transport: createAxiosTransport(axios) });
`;

/** The helpers the wrappers may emit, each with the helpers it calls. */
const HELPERS = {
  bindClient: {
    uses: [],
    source: `
/**
 * Wrap a generated request function so every call goes through \`client\`.
 * Each function takes a single options object, so the client is merged into it.
 */
function bindClient<F extends (...args: never[]) => unknown>(fn: F, client: ClientInstance): F {
  return ((options?: object) =>
    (fn as unknown as (options: object) => unknown)({ ...options, client })) as unknown as F;
}
`,
  },
  bindOperation: {
    uses: ['bindClient'],
    source: `
/**
 * \`bindClient\`, plus the operation's tree (its query or mutation options, and
 * its input schema) as properties of the bound function. One call does both:
 * nesting \`bindClient(...)\` inside \`Object.assign(...)\` would make
 * TypeScript fix the request function's \`ThrowOnError\` type parameter.
 */
function bindOperation<F extends (...args: never[]) => unknown, T extends object>(
  fn: F,
  client: ClientInstance,
  tree: T,
): F & T {
  return Object.assign(bindClient(fn, client), tree);
}
`,
  },
  bindOptions: {
    uses: [],
    source: `
/**
 * Wrap a generated \`xQueryOptions\` or \`xMutationOptions\` so the query or
 * mutation it describes calls through \`client\`, outside React too
 * (\`queryClient.ensureQueryData(...)\` in a route loader). The request config
 * it takes at \`configIndex\` gets \`client\`: 1 for query options whose
 * request data comes first, otherwise 0.
 */
function bindOptions<F extends (...args: never[]) => unknown>(
  fn: F,
  client: ClientInstance,
  configIndex: number,
): F {
  return ((...args: unknown[]) =>
    (fn as unknown as (...rest: unknown[]) => unknown)(
      ...Array.from({ length: configIndex }, (_, i) => args[i]),
      { ...(args[configIndex] as object | undefined), client },
    )) as unknown as F;
}
`,
  },
  bindHook: {
    uses: [],
    source: `
/**
 * Wrap a generated react-query hook so it reads the client from
 * \`ApiClientContext\` and forwards it through the hook's \`client\` request
 * config. \`optionsIndex\` is where the hook takes its options object: 1 for a
 * query hook with a leading request argument, otherwise 0. (\`hook.length\`
 * can't tell: a defaulted request argument doesn't count towards it.)
 */
function bindHook<F extends (...args: never[]) => unknown>(hook: F, optionsIndex: number): F {
  return ((...args: unknown[]) => {
    // eslint-disable-next-line react-hooks/rules-of-hooks
    const ctx = React.useContext(ApiClientContext);
    if (!ctx) {
      throw new Error(
        'nestjs-endpoints react-query hooks must be used within an <ApiClientProvider>.',
      );
    }
    const options = (args[optionsIndex] ?? {}) as Record<string, unknown>;
    const config = (options.client ?? {}) as Record<string, unknown>;
    return (hook as unknown as (...rest: unknown[]) => unknown)(
      ...Array.from({ length: optionsIndex }, (_, i) => args[i]),
      { ...options, client: { ...config, client: ctx.client } },
    );
  }) as unknown as F;
}
`,
  },
} as const satisfies Record<string, { uses: readonly string[]; source: string }>;

type Helper = keyof typeof HELPERS;

/** The source of `used` and of every helper they call, in a fixed order. */
function helperSource(used: ReadonlySet<Helper>): string {
  const all = new Set<Helper>();
  const add = (name: Helper) => {
    all.add(name);
    HELPERS[name].uses.forEach((dep) => add(dep as Helper));
  };
  used.forEach(add);
  return (Object.keys(HELPERS) as Helper[])
    .filter((name) => all.has(name))
    .map((name) => HELPERS[name].source)
    .join('');
}

/**
 * Whether the generated types of this client hold a type Kubb names `name`:
 * re-exporting one of the runtime's under the same name would hide it. Only
 * the shared schemas this client's operations reach are generated, and Kubb's
 * casing rules are its own, so any name that reads the same counts.
 */
function generatesType(
  descriptors: readonly EndpointDescriptor[],
  shared: SharedSchemas,
  name: string,
): boolean {
  const normalize = (value: string) => value.replace(/[^A-Za-z0-9]/g, '').toLowerCase();
  const generated = reachableSchemas(
    descriptors.flatMap((d) => rootsOf(d, shared.renamed)),
    shared,
  );
  return Object.keys(generated).some((schema) => normalize(schema) === normalize(name));
}

/**
 * `export { isResponseError, ResponseError } from <runtime>`, leaving out a
 * name the client's generated types already use.
 */
function responseErrorExport(params: {
  descriptors: readonly EndpointDescriptor[];
  shared: SharedSchemas;
  runtimeImport: string;
}): string {
  const { descriptors, shared, runtimeImport } = params;
  const names = ['isResponseError', 'ResponseError'].filter(
    (name) => !generatesType(descriptors, shared, name),
  );
  return names.length ? `export { ${names.join(', ')} } from '${runtimeImport}';\n` : '';
}

/**
 * Build the consumer-facing axios wrapper source. It imports the Kubb-generated
 * request functions (the flat `clients` barrel) plus Kubb's runtime, then
 * assembles the namespaced client object, binding the instance's Kubb client
 * into each operation via `bindClient`. The bucket tree, name normalization,
 * and collision checks are shared with the react-query wrapper (see
 * `./buckets`).
 */
export function buildAxiosWrapperSource(params: {
  descriptors: readonly EndpointDescriptor[];
  /**
   * The app's shared schemas; those the descriptors reach become generated
   * types.
   */
  shared: SharedSchemas;
  /** Import specifier for the generated `clients` barrel (no extension). */
  clientsImport: string;
  /** Import specifier for Kubb's runtime, `.kubb/client` (no extension). */
  runtimeImport: string;
  /** Import specifier for the generated barrel whose types are re-exported. */
  typesImport: string;
}): string {
  const { descriptors, shared, clientsImport, runtimeImport, typesImport } = params;

  const buildExpr = buildClientObjectExpression({
    descriptors,
    tagDescriptions: tagDescriptions(),
    plainAccess: (src) => `bindClient(_ops.${src}, _client)`,
    hookAccess: null,
    rootExtras: ['axios: _axios'],
  });

  return (
    HEADER_AXIOS +
    `import Axios from 'axios';\n` +
    `import type { AxiosInstance, CreateAxiosDefaults } from 'axios';\n` +
    `import * as _ops from '${clientsImport}';\n` +
    `import {\n` +
    `  createAxiosTransport,\n` +
    `  createClient,\n` +
    `  type ClientInstance,\n` +
    `} from '${runtimeImport}';\n\n` +
    `export type * from '${typesImport}';\n` +
    responseErrorExport({ descriptors, shared, runtimeImport }) +
    AXIOS_INSTANCE_HELPER +
    helperSource(new Set(['bindClient'])) +
    `\n/**\n` +
    ` * A client for the API. \`config\` is axios defaults (\`baseURL\`, \`headers\`, …)\n` +
    ` * for a new axios instance, or an axios instance to send through.\n` +
    ` */\n` +
    `export const createApiClient = (config?: CreateAxiosDefaults | AxiosInstance) => {\n` +
    `  const _axios = _axiosFor(config);\n` +
    `  const _client = _clientFor(_axios);\n` +
    `  return ${buildExpr};\n` +
    `};\n\n` +
    `export type ApiClient = ReturnType<typeof createApiClient>;\n`
  );
}

/**
 * Build the consumer-facing react-query wrapper source. Each namespace bucket
 * carries, per operation:
 *
 * - the request function (bound to the instance's Kubb client via
 *   `bindOperation`), which also holds the operation's tree:
 *   - an `endpoint.query()`: `queryKey` and `queryOptions`, or an
 *     `endpoint.mutation()`: `mutationKey` and `mutationOptions` (bound via
 *     `bindOptions`);
 *   - with input or search parameters: `schemas.input` and `schemas.query`,
 *     their JSON Schema from `schemas.ts`;
 * - its paired React Query hook (`bindHook`, which reads the client from
 *   `ApiClientContext`).
 *
 * It also exports `useApiClient` + `ApiClientProvider`. The request functions
 * come from the generated `clients` barrel, the same ones the standalone axios
 * client exposes; the hooks and the key/options helpers come from the
 * generated `hooks` barrel and return unwrapped data.
 */
export function buildReactQueryWrapperSource(params: {
  descriptors: readonly EndpointDescriptor[];
  /**
   * The app's shared schemas; those the descriptors reach become generated
   * types.
   */
  shared: SharedSchemas;
  /** Import for the generated `clients` barrel (request functions). */
  opsImport: string;
  /** Import for the generated `hooks` barrel. */
  hooksImport: string;
  /** Import for Kubb's runtime, `.kubb/client`. */
  runtimeImport: string;
  /** Import for the generated barrel whose types are re-exported. */
  typesImport: string;
  /** Import for the emitted `schemas.ts` module. */
  schemasImport: string;
  /**
   * The react-query plugin options, which decide the operations Kubb gives
   * query or mutation helpers (`query`, `mutation`, `include`, `exclude`,
   * `override`).
   */
  pluginOptions: OperationKindOptions;
  /** Source names of the operations `schemas.ts` has schemas for. */
  inputSchemaNames: ReadonlySet<string>;
}): string {
  const {
    descriptors,
    shared,
    opsImport,
    hooksImport,
    runtimeImport,
    typesImport,
    schemasImport,
    pluginOptions,
    inputSchemaNames,
  } = params;
  const kinds = operationKinds(descriptors, pluginOptions);
  // The helpers the operations below use, so the wrapper declares nothing
  // more: an unused declaration fails a consumer's `noUnusedLocals`.
  const helpers = new Set<Helper>();

  const buildExpr = buildClientObjectExpression({
    descriptors,
    tagDescriptions: tagDescriptions(),
    plainAccess: (src, { operationId, hasRequest }) => {
      const tree: string[] = [];
      const kind = kinds.get(operationId);
      if (kind === 'query') {
        helpers.add('bindOptions');
        tree.push(
          `queryKey: _hooks.${src}QueryKey`,
          `queryOptions: bindOptions(_hooks.${src}QueryOptions, _client, ${hasRequest ? 1 : 0})`,
        );
      } else if (kind === 'mutation') {
        helpers.add('bindOptions');
        tree.push(
          `mutationKey: _hooks.${src}MutationKey`,
          `mutationOptions: bindOptions(_hooks.${src}MutationOptions, _client, 0)`,
        );
      }
      if (inputSchemaNames.has(src)) {
        tree.push(`schemas: _schemas.${src}`);
      }
      if (!tree.length) {
        helpers.add('bindClient');
        return `bindClient(_ops.${src}, _client)`;
      }
      helpers.add('bindOperation');
      return `bindOperation(_ops.${src}, _client, { ${tree.join(', ')} })`;
    },
    // Kubb generates no hook for an operation it makes neither a query nor a
    // mutation. A query hook takes its request data first when the operation
    // has any; mutation hooks get theirs through `mutate()`.
    hookAccess: (src, { operationId, hasRequest }) => {
      const kind = kinds.get(operationId);
      if (!kind) {
        return undefined;
      }
      helpers.add('bindHook');
      return `bindHook(_hooks.${src}, ${kind === 'query' && hasRequest ? 1 : 0})`;
    },
    // `[_CTX]` carries the instance's client/axios pair so `ApiClientProvider`
    // can put it into React context. It's a module-private `unique symbol`, so
    // it's hidden from consumers and absent from `Object.keys`, but — being an
    // enumerable own property — it survives object spread and stays typed (no
    // cast needed to read it back).
    rootExtras: ['axios: _axios', '[_CTX]: _ctx'],
  });

  return (
    HEADER_REACT_QUERY +
    `import * as React from 'react';\n` +
    `import Axios from 'axios';\n` +
    `import type { AxiosInstance, CreateAxiosDefaults } from 'axios';\n` +
    `import * as _ops from '${opsImport}';\n` +
    `import * as _hooks from '${hooksImport}';\n` +
    (inputSchemaNames.size ? `import * as _schemas from '${schemasImport}';\n` : '') +
    `import {\n` +
    `  createAxiosTransport,\n` +
    `  createClient,\n` +
    `  type ClientInstance,\n` +
    `} from '${runtimeImport}';\n\n` +
    `export type * from '${typesImport}';\n` +
    responseErrorExport({ descriptors, shared, runtimeImport }) +
    (generatesType(descriptors, shared, 'InputSchema')
      ? ''
      : `export type { InputSchema } from '${schemasImport}';\n`) +
    AXIOS_INSTANCE_HELPER +
    `\ntype ApiClientContextValue = { client: ClientInstance; axios: AxiosInstance };\n\n` +
    `const ApiClientContext = React.createContext<ApiClientContextValue | null>(null);\n` +
    helperSource(helpers) +
    `\nconst _CTX = Symbol('nestjs-endpoints:client-ctx');\n\n` +
    `const _build = (_ctx: ApiClientContextValue) => {\n` +
    `  const { client: _client, axios: _axios } = _ctx;\n` +
    `  return ${buildExpr};\n` +
    `};\n\n` +
    `/**\n` +
    ` * A client for the API. \`config\` is axios defaults (\`baseURL\`, \`headers\`, …)\n` +
    ` * for a new axios instance, or an axios instance to send through.\n` +
    ` */\n` +
    `export const createApiClient = (config?: CreateAxiosDefaults | AxiosInstance) => {\n` +
    `  const _axios = _axiosFor(config);\n` +
    `  return _build({ client: _clientFor(_axios), axios: _axios });\n` +
    `};\n\n` +
    `export type ApiClient = ReturnType<typeof createApiClient>;\n\n` +
    `export const useApiClient = (): ApiClient => {\n` +
    `  const _ctx = React.useContext(ApiClientContext);\n` +
    `  if (!_ctx) {\n` +
    `    throw new Error(\n` +
    `      'useApiClient must be used within an <ApiClientProvider>.',\n` +
    `    );\n` +
    `  }\n` +
    `  return React.useMemo(() => _build(_ctx), [_ctx]);\n` +
    `};\n\n` +
    `export const ApiClientProvider = ({\n` +
    `  client,\n` +
    `  children,\n` +
    `}: {\n` +
    `  client: ApiClient;\n` +
    `  children: React.ReactNode;\n` +
    `}) =>\n` +
    `  React.createElement(ApiClientContext.Provider, { value: client[_CTX] }, children);\n`
  );
}
