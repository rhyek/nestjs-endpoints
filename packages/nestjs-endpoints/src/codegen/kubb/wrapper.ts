import { settings } from '../../consts.js';
import type { EndpointDescriptor } from '../../descriptors.js';
import { reachableSchemas, type SharedSchemas } from '../../shared-schemas.js';
import { rootsOf } from './adapter.js';
import { buildClientObjectExpression } from './buckets.js';
import { operationKinds, type OperationKindOptions } from './operation-kind.js';

/**
 * The descriptions router modules give their namespaces, keyed by the chain
 * joined with `/`, written above each namespace bucket.
 */
function tagDescriptions(): Map<string, string> {
  return new Map(settings.openapi.tags.map(({ name, description }) => [name, description]));
}

/**
 * The descriptions a wrapper for `descriptors` writes above its buckets:
 * those of every namespace chain, and each of its prefixes, the descriptors
 * sit under. Keyed like `descriptions`.
 */
export function printedTagDescriptions(
  descriptors: readonly EndpointDescriptor[],
  descriptions: ReadonlyMap<string, string> = tagDescriptions(),
): Record<string, string> {
  const printed: Record<string, string> = {};
  for (const { namespaceChain } of descriptors) {
    for (let i = 1; i <= namespaceChain.length; i++) {
      const key = namespaceChain.slice(0, i).join('/');
      const description = descriptions.get(key);
      if (description) {
        printed[key] = description;
      }
    }
  }
  return printed;
}

/**
 * Build the consumer-facing axios wrapper source. It imports the Kubb-generated
 * request functions (the flat `clients` barrel) plus the runtime, then
 * assembles the namespaced client object — binding the per-instance axios
 * client into each operation via `bindClient`. The bucket tree, name
 * normalization, and collision checks are shared with the react-query wrapper
 * (see `./buckets`).
 */
export function buildAxiosWrapperSource(params: {
  descriptors: readonly EndpointDescriptor[];
  /** Import specifier for the generated `clients` barrel (no extension). */
  clientsImport: string;
  /** Import specifier for the emitted runtime module (no extension). */
  runtimeImport: string;
  /** Import specifier for the generated barrel whose types are re-exported. */
  typesImport: string;
}): string {
  const { descriptors, clientsImport, runtimeImport, typesImport } = params;

  const buildExpr = buildClientObjectExpression({
    descriptors,
    tagDescriptions: tagDescriptions(),
    plainAccess: (src) => `bindClient(_ops.${src}, _request)`,
    hookAccess: null,
    rootExtras: ['axios: _axios'],
  });

  return (
    `/**\n` +
    ` * Generated by nestjs-endpoints — do not edit manually.\n` +
    ` *\n` +
    ` * The Kubb-generated request functions and types live in the sibling\n` +
    ` * directory; this file is the consumer-facing entry point and exposes the\n` +
    ` * namespaced client surface plus the \`ApiClient\` type.\n` +
    ` */\n` +
    `import * as _ops from '${clientsImport}';\n` +
    `import { bindClient, createBoundClient } from '${runtimeImport}';\n\n` +
    `export type * from '${typesImport}';\n\n` +
    `export const createApiClient = (\n` +
    `  ...args: Parameters<typeof createBoundClient>\n` +
    `) => {\n` +
    `  const { request: _request, axios: _axios } = createBoundClient(...args);\n` +
    `  return ${buildExpr};\n` +
    `};\n\n` +
    `export type ApiClient = ReturnType<typeof createApiClient>;\n`
  );
}

/**
 * Build the consumer-facing react-query wrapper source. Each namespace bucket
 * carries, per operation:
 *
 * - the imperative axios method (full `AxiosResponse`, bound to the instance
 *   via `bindOperation`), which also holds the operation's tree:
 *   - an `endpoint.query()`: `queryKey` and `queryOptions` (bound via
 *     `bindQueryOptions`);
 *   - an `endpoint.mutation()`: `mutationKey` and `mutationOptions` (bound
 *     via `bindMutationOptions`);
 *   - with input or search parameters: `schemas.input` and `schemas.query`,
 *     their JSON Schema from `schemas.ts`;
 * - its paired React Query hook (`bindHook`, which reads the bound client from
 *   `ApiClientContext`).
 *
 * It also exports `useApiClient` + `ApiClientProvider`. The axios methods come
 * from the generated `clients` barrel, the same request functions the
 * standalone axios client exposes; the hooks and the key/options helpers come
 * from the generated `hooks` barrel and return unwrapped data.
 */
export function buildReactQueryWrapperSource(params: {
  descriptors: readonly EndpointDescriptor[];
  /**
   * The app's shared schemas; those the descriptors reach become generated
   * types.
   */
  shared: SharedSchemas;
  /** Import for the generated `clients` barrel (axios methods). */
  opsImport: string;
  /** Import for the generated `hooks` barrel. */
  hooksImport: string;
  /** Import for the emitted runtime module. */
  runtimeImport: string;
  /** Import for the generated barrel whose types are re-exported. */
  typesImport: string;
  /** Import for the emitted `schemas.ts` module. */
  schemasImport: string;
  /**
   * The react-query plugin options, which decide the operations Kubb gives
   * query or mutation helpers (`query`, `mutation`, `include`, `exclude`,
   * `override`).
   */
  pluginOptions: OperationKindOptions;
  /** Source names of the operations `schemas.ts` has schemas for. */
  inputSchemaNames: ReadonlySet<string>;
}): string {
  const {
    descriptors,
    shared,
    opsImport,
    hooksImport,
    runtimeImport,
    typesImport,
    schemasImport,
    pluginOptions,
    inputSchemaNames,
  } = params;
  const kinds = operationKinds(descriptors, pluginOptions);
  // A shared schema of the app's own that Kubb names `InputSchema` comes
  // through `export type *`; re-exporting the runtime's would hide it. Only
  // the shared schemas this client's operations reach are generated. Kubb's
  // casing rules are its own, so any name that reads `inputschema` counts.
  const generated = reachableSchemas(
    descriptors.flatMap((d) => rootsOf(d, shared.renamed)),
    shared,
  );
  const ownsInputSchema = Object.keys(generated).some(
    (name) => name.replace(/[^A-Za-z0-9]/g, '').toLowerCase() === 'inputschema',
  );
  // The binders the operations below use, so the wrapper imports nothing
  // more: an unused import fails a consumer's `noUnusedLocals`.
  const binders = new Set<string>();

  const buildExpr = buildClientObjectExpression({
    descriptors,
    tagDescriptions: tagDescriptions(),
    plainAccess: (src, { operationId, hasRequest }) => {
      const tree: string[] = [];
      const kind = kinds.get(operationId);
      if (kind === 'query') {
        binders.add('bindQueryOptions');
        tree.push(
          `queryKey: _hooks.${src}QueryKey`,
          `queryOptions: bindQueryOptions(_hooks.${src}QueryOptions, _request, ${hasRequest})`,
        );
      } else if (kind === 'mutation') {
        binders.add('bindMutationOptions');
        tree.push(
          `mutationKey: _hooks.${src}MutationKey`,
          `mutationOptions: bindMutationOptions(_hooks.${src}MutationOptions, _request)`,
        );
      }
      if (inputSchemaNames.has(src)) {
        tree.push(`schemas: _schemas.${src}`);
      }
      if (!tree.length) {
        binders.add('bindClient');
        return `bindClient(_ops.${src}, _request)`;
      }
      binders.add('bindOperation');
      return `bindOperation(_ops.${src}, _request, { ${tree.join(', ')} })`;
    },
    // Kubb generates no hook for an operation it makes neither a query nor a
    // mutation. A query hook takes its request data first when the operation
    // has any; mutation hooks get theirs through `mutate()`.
    hookAccess: (src, { operationId, hasRequest }) => {
      const kind = kinds.get(operationId);
      if (!kind) {
        return undefined;
      }
      binders.add('bindHook');
      return `bindHook(_hooks.${src}, ${kind === 'query' && hasRequest ? 1 : 0})`;
    },
    // `[_CTX]` carries the bound client/axios pair so `ApiClientProvider` can
    // put it into React context. It's a module-private `unique symbol`, so it's
    // hidden from consumers and absent from `Object.keys`, but — being an
    // enumerable own property — it survives object spread and stays typed (no
    // cast needed to read it back).
    rootExtras: ['axios: _axios', '[_CTX]: _ctx'],
  });

  return (
    `/**\n` +
    ` * Generated by nestjs-endpoints — do not edit manually.\n` +
    ` *\n` +
    ` * The Kubb-generated request functions, hooks, and types live in the\n` +
    ` * sibling directory; this file is the consumer-facing entry point and\n` +
    ` * exposes the namespaced client surface (axios methods, each with its\n` +
    ` * query or mutation options and input schema, + paired hooks) plus\n` +
    ` * \`ApiClient\`, \`useApiClient\`, and \`ApiClientProvider\`.\n` +
    ` */\n` +
    `import * as React from 'react';\n` +
    `import * as _ops from '${opsImport}';\n` +
    `import * as _hooks from '${hooksImport}';\n` +
    (inputSchemaNames.size ? `import * as _schemas from '${schemasImport}';\n` : '') +
    `import {\n` +
    ['ApiClientContext', ...[...binders].sort(), 'createBoundClient']
      .map((name) => `  ${name},\n`)
      .join('') +
    `  type ApiClientContextValue,\n` +
    `} from '${runtimeImport}';\n\n` +
    `export type * from '${typesImport}';\n` +
    (ownsInputSchema ? '\n' : `export type { InputSchema } from '${runtimeImport}';\n\n`) +
    `const _CTX = Symbol('nestjs-endpoints:client-ctx');\n\n` +
    `const _build = (_ctx: ApiClientContextValue) => {\n` +
    `  const { request: _request, axios: _axios } = _ctx;\n` +
    `  return ${buildExpr};\n` +
    `};\n\n` +
    `export const createApiClient = (\n` +
    `  ...args: Parameters<typeof createBoundClient>\n` +
    `) => _build(createBoundClient(...args));\n\n` +
    `export type ApiClient = ReturnType<typeof createApiClient>;\n\n` +
    `export const useApiClient = (): ApiClient => {\n` +
    `  const _ctx = React.useContext(ApiClientContext);\n` +
    `  if (!_ctx) {\n` +
    `    throw new Error(\n` +
    `      'useApiClient must be used within an <ApiClientProvider>.',\n` +
    `    );\n` +
    `  }\n` +
    `  return React.useMemo(() => _build(_ctx), [_ctx]);\n` +
    `};\n\n` +
    `export const ApiClientProvider = ({\n` +
    `  client,\n` +
    `  children,\n` +
    `}: {\n` +
    `  client: ApiClient;\n` +
    `  children: React.ReactNode;\n` +
    `}) =>\n` +
    `  React.createElement(ApiClientContext.Provider, { value: client[_CTX] }, children);\n`
  );
}
