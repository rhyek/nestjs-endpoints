let dir: string;

beforeEach(async () => {
  dir = await mkdtemp(path.join(os.tmpdir(), 'nestjs-endpoints-generate-'));
});
afterEach(() => rm(dir, { recursive: true, force: true }));

function descriptor(
  fields: Pick<EndpointDescriptor, 'operationId' | 'kind' | 'method' | 'path'>,
): EndpointDescriptor {
  return {
    pathParams: [],
    namespaceChain: [],
    tags: [],
    summary: '',
    outputs: [
      {
        status: 200,
        schema: { json: { type: 'string' }, components: {} },
      },
    ],
    ...fields,
  };
}

test("the hooks, their options and customOptions' hook options follow each operation's builder, not its method", async () => {
  // A POST query and a GET mutation: the kind the method alone would give
  // each is the other one. A user override with a string pattern, which
  // `@kubb/core` reads as a regular expression and the plugin's hook options
  // compare with `===`, turns the third one's query off in both.
  const descriptors = [
    descriptor({
      operationId: 'ItemsList',
      kind: 'query',
      method: 'post',
      path: '/items/list',
    }),
    descriptor({
      operationId: 'ItemsRemove',
      kind: 'mutation',
      method: 'get',
      path: '/items/remove',
    }),
    descriptor({
      operationId: 'ItemsCount',
      kind: 'query',
      method: 'post',
      path: '/items/count',
    }),
  ];
  const outputFile = path.join(dir, 'client.tsx');
  await generateReactQueryClient({
    descriptors,
    shared: mergeSharedSchemas(descriptors),
    outputFile,
    options: {
      customOptions: { importPath: './custom-hook-options' },
      override: [
        {
          type: 'operationId',
          pattern: '^ItemsCount$',
          options: { query: false },
        },
      ],
    },
    hash: 'x',
  });
  const read = (file: string) => readFile(path.join(dir, file), 'utf8');

  // One module per plugin, and no directory of files per operation. `customOptions` adds
  // its two.
  expect((await readdir(path.join(dir, 'client'))).sort()).toEqual([
    '.kubb',
    'HookOptions.ts',
    'clients.ts',
    'context.ts',
    'custom-hook-options.ts',
    'hooks.ts',
    'schemas.ts',
    'types.ts',
  ]);

  const hooks = await read('client/hooks.ts');
  expect(hooks).toContain('export function useItemsList');
  expect(hooks).toContain('useQuery(');
  expect(hooks).toContain('export function useItemsRemove');
  expect(hooks).toContain('useMutation<');
  expect(hooks).not.toMatch(/itemsCount|ItemsCount/);

  const hookOptions = await read('client/HookOptions.ts');
  expect(hookOptions).toContain('itemsListQueryOptions');
  expect(hookOptions).toContain('itemsRemoveMutationOptions');
  expect(hookOptions).not.toContain('itemsListMutationOptions');
  expect(hookOptions).not.toContain('itemsRemoveQueryOptions');
  expect(hookOptions).not.toMatch(/itemsCount/i);

  // The wrapper refers to the helpers Kubb generated, and no others.
  expect(await read('client.tsx')).toContain('itemsCount: bindClient(_ops.itemsCount, _client),');
}, 60_000);

test('a React Query client keeps its React context in a module of its own', async () => {
  const list = descriptor({ operationId: 'List', kind: 'query', method: 'post', path: '/list' });
  await generateReactQueryClient({
    descriptors: [list],
    shared: mergeSharedSchemas([list]),
    outputFile: path.join(dir, 'client.tsx'),
    hash: 'x',
  });
  const context = await readFile(path.join(dir, 'client', 'context.ts'), 'utf8');
  expect(context).toMatch(/^\/\*\*\n \* Generated by nestjs-endpoints — do not edit manually\./);
  expect(context).toMatch(/^import \* as React from 'react';?$/m);
  expect(context).toMatch(/^import type \{ AxiosInstance \} from 'axios';?$/m);
  expect(context).toMatch(/^import type \{ ClientInstance \} from '\.\/\.kubb\/client';?$/m);
  expect(context).toContain(
    'export type ApiClientContextValue = { client: ClientInstance; axios: AxiosInstance };',
  );
  expect(context).toContain(
    'export const ApiClientContext = React.createContext<ApiClientContextValue | null>(null);',
  );
  expect(context).toContain(
    "export const CLIENT_CONTEXT: unique symbol = Symbol('nestjs-endpoints:client-ctx');",
  );
  expect(await readFile(path.join(dir, 'client.tsx'), 'utf8')).toContain(
    `import { ApiClientContext, CLIENT_CONTEXT as _CTX, type ApiClientContextValue } from './client/context';`,
  );
}, 60_000);

// A front end's dev server reloads the modules whose files were written. One that is written
// with what it already held would be reloaded for nothing, and the React context among them
// would be made again under a page that still renders the provider of the one before.
describe('a client generated again, into the folder it is in', () => {
  const list = descriptor({ operationId: 'List', kind: 'query', method: 'post', path: '/list' });
  const count = descriptor({ operationId: 'Count', kind: 'query', method: 'post', path: '/count' });

  const outputFile = () => path.join(dir, 'client.tsx');
  const generate = (descriptors: EndpointDescriptor[], hash: string) =>
    generateReactQueryClient({
      descriptors,
      shared: mergeSharedSchemas(descriptors),
      outputFile: outputFile(),
      hash,
    });

  /** Every file of the client, by its path from the folder, with when it was written. */
  async function written(): Promise<Record<string, number>> {
    const entries = await readdir(dir, { recursive: true, withFileTypes: true });
    const files: Record<string, number> = {};
    for (const entry of entries.filter((e) => e.isFile())) {
      const file = path.join(entry.parentPath, entry.name);
      files[path.relative(dir, file)] = (await stat(file)).mtimeMs;
    }
    return files;
  }

  /** Long enough for a file written again to have a later time. */
  const later = () => new Promise((resolve) => setTimeout(resolve, 20));

  test('rewrites the files that changed, and leaves the others as they were', async () => {
    await generate([list], 'one');
    const first = await written();
    await later();

    await generate([list, count], 'two');

    const second = await written();
    const changed = Object.keys(second).filter((file) => second[file] !== first[file]);
    expect(changed.sort()).toEqual([
      'client.tsx',
      'client/clients.ts',
      'client/hooks.ts',
      'client/types.ts',
    ]);
    expect(Object.keys(second).sort()).toEqual(Object.keys(first).sort());
    expect(Object.keys(second)).toContain('client/context.ts');
    expect(Object.keys(second)).toContain('client/.kubb/client.ts');
  }, 60_000);

  test('removes the files it no longer writes', async () => {
    await generate([list], 'one');
    expect(Object.keys(await written())).toContain('client/hooks.ts');

    await generate([], 'two');

    const files = Object.keys(await written());
    for (const gone of ['client/clients.ts', 'client/hooks.ts', 'client/types.ts']) {
      expect(files).not.toContain(gone);
    }
    expect(files).toContain('client/context.ts');
    expect(files).toContain('client/.kubb/client.ts');
  }, 60_000);

  test('keeps what it wrote when its `outputFile` is relative to the working directory', async () => {
    const relative = path.relative(process.cwd(), outputFile());
    const build = () =>
      generateReactQueryClient({
        descriptors: [list],
        shared: mergeSharedSchemas([list]),
        outputFile: relative,
        hash: 'one',
      });
    await build();
    const first = Object.keys(await written());

    await build();

    expect(first).toContain('client/hooks.ts');
    expect(Object.keys(await written())).toEqual(first);
  }, 60_000);

  test('as another kind of client, removes what only the first kind has', async () => {
    await generate([list], 'one');

    await generateAxiosClient({
      descriptors: [list],
      shared: mergeSharedSchemas([list]),
      outputFile: outputFile(),
      hash: 'two',
    });

    const files = Object.keys(await written());
    for (const gone of ['client/context.ts', 'client/hooks.ts', 'client/schemas.ts']) {
      expect(files).not.toContain(gone);
    }
    expect(files).toContain('client/clients.ts');
  }, 60_000);
});

// Each option makes Kubb write modules of its own, which a build must not take for what an
// earlier build left.
describe('a React Query client with options of its own, generated again', () => {
  const list = descriptor({ operationId: 'List', kind: 'query', method: 'post', path: '/list' });
  const create = descriptor({
    operationId: 'Create',
    kind: 'mutation',
    method: 'post',
    path: '/create',
  });

  /** Every file of the client, by its path from the folder. */
  async function files(): Promise<string[]> {
    const entries = await readdir(dir, { recursive: true, withFileTypes: true });
    return entries
      .filter((e) => e.isFile())
      .map((e) => path.relative(dir, path.join(e.parentPath, e.name)))
      .sort();
  }

  /** The relative imports of the client's files that name no file it has. */
  async function missingImports(): Promise<string[]> {
    const missing: string[] = [];
    for (const file of await files()) {
      const source = await readFile(path.join(dir, file), 'utf8');
      for (const [, specifier] of source.matchAll(/from '(\.[^']*)'/g)) {
        const target = path.join(path.dirname(path.join(dir, file)), specifier);
        const found = await Promise.all(
          ['', '.ts', '.tsx'].map((extension) =>
            stat(target + extension).then(
              (s) => s.isFile(),
              () => false,
            ),
          ),
        );
        if (!found.includes(true)) {
          missing.push(`${file}: ${specifier}`);
        }
      }
    }
    return missing;
  }

  test.each<[string, ReactQueryPluginOptions]>([
    ['infinite', { infinite: {} }],
    ['suspense', { suspense: {} }],
    ['customOptions', { customOptions: { importPath: './custom-hook-options' } }],
    ['mutation off', { mutation: false }],
  ])(
    'with %s, keeps every file it writes',
    async (_, options) => {
      const generate = (hash: string) =>
        generateReactQueryClient({
          descriptors: [list, create],
          shared: mergeSharedSchemas([list, create]),
          outputFile: path.join(dir, 'client.tsx'),
          options,
          hash,
        });

      await generate('one');
      const first = await files();
      expect(await missingImports()).toEqual([]);

      await generate('two');

      expect(await files()).toEqual(first);
      expect(await missingImports()).toEqual([]);
    },
    60_000,
  );

  test('keeps what the user wrote in the module `customOptions` names', async () => {
    const generate = (hash: string) =>
      generateReactQueryClient({
        descriptors: [list],
        shared: mergeSharedSchemas([list]),
        outputFile: path.join(dir, 'client.tsx'),
        options: { customOptions: { importPath: './custom-hook-options' } },
        hash,
      });
    const custom = path.join(dir, 'client', 'custom-hook-options.ts');

    await generate('one');
    const filled = (await readFile(custom, 'utf8')).replace('// TODO', '// Filled in. TODO');
    await writeFile(custom, filled);
    await generate('two');

    expect(await readFile(custom, 'utf8')).toBe(filled);
  }, 60_000);
});

// A client's build holds nothing once it is done: the app keeps running after it. Kubb's
// `build()` runs `safeBuild()`, which disposes of the build's driver itself, whether a plugin
// failed or not; one that fails as it starts leaves no driver to dispose of.
describe("Kubb's build", () => {
  const failsToStart = defineExtension({
    kind: 'plugin',
    meta: { name: 'plugin-fails-to-start' },
    setup() {
      throw new Error('a plugin failed');
    },
  })({});
  const failsAsItRuns = defineExtension({
    kind: 'plugin',
    meta: { name: 'plugin-fails-as-it-runs' },
    setup(options) {
      addGenerator(
        defineGenerator({
          name: 'fails',
          operation() {
            throw new Error('a generator failed');
          },
        }),
      );
      return options;
    },
  })({});
  const list = descriptor({ operationId: 'List', kind: 'query', method: 'post', path: '/list' });

  test.each([
    ['succeeds', []],
    ['fails as a plugin starts', [failsToStart]],
    ['fails as a plugin runs', [failsAsItRuns]],
  ])('releases what it holds when it %s', async (_, plugins) => {
    const kubb = createKubb({
      root: dir,
      input: {},
      adapter: adapterEndpoints(
        buildInputNode({ descriptors: [list], shared: mergeSharedSchemas([list]) }),
      ),
      output: { path: path.join(dir, 'out'), clean: false, format: false, lint: false },
      plugins,
    });
    const failure = await kubb.build().then(
      () => undefined,
      (error: unknown) => error,
    );
    expect(failure === undefined).toBe(plugins.length === 0);
    expect(() => kubb.driver).toThrow('setup() must be called before accessing driver');
  });
});
