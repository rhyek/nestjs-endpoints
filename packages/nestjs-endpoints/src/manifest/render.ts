import path from 'node:path';

/**
 * How the manifest's `import()` specifiers spell extensions.
 *
 * - `js`: `./a.endpoint.ts` is imported as `./a.endpoint.js`. What tsc,
 *   tsx, swc and Vite all resolve, and what compiled output needs.
 * - `ts`: imported as written. For Node's native type stripping, which
 *   needs real `.ts` specifiers (and `allowImportingTsExtensions`).
 */
export type ImportExtension = 'js' | 'ts';

export const DEFAULT_IMPORT_EXTENSION: ImportExtension = 'js';

export const MANIFEST_FILE_NAME = 'endpoints.gen.ts';

const COMPILED_EXTENSION: Record<string, string> = {
  '.ts': '.js',
  '.mts': '.mjs',
};

function importSpecifier(key: string, importExtension: ImportExtension) {
  const ext = path.extname(key);
  const specifier =
    importExtension === 'js' && COMPILED_EXTENSION[ext]
      ? key.slice(0, -ext.length) + COMPILED_EXTENSION[ext]
      : key;
  return `./${specifier}`;
}

/** The source of an endpoint manifest listing `files` (sorted, relative). */
export function renderManifest(files: readonly string[], importExtension: ImportExtension): string {
  // JSON.stringify quotes keys and specifiers: file names routinely carry
  // `$` (path params), and may carry quotes or backslashes.
  const entries = files.map(
    (key) =>
      `    ${JSON.stringify(key)}: () => import(${JSON.stringify(importSpecifier(key, importExtension))}),`,
  );
  return [
    '// Generated by nestjs-endpoints. Do not edit: the app keeps this file in',
    '// sync while it runs in development, and `npx nestjs-endpoints generate`',
    '// rewrites it on demand.',
    'import { registerEndpointManifest } from "nestjs-endpoints";',
    '',
    'registerEndpointManifest(import.meta.url, {',
    `  importExtension: ${JSON.stringify(importExtension)},`,
    '  files: {',
    ...entries,
    '  },',
    '});',
    '',
  ].join('\n');
}
