import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { scanRoutingFiles } from './scan';

/**
 * How the manifest's `import()` specifiers spell extensions.
 *
 * - `js`: `./a.endpoint.ts` is imported as `./a.endpoint.js`. What tsc,
 *   tsx, swc and Vite all resolve, and what compiled output needs.
 * - `ts`: imported as written. For Node's native type stripping, which
 *   needs real `.ts` specifiers (and `allowImportingTsExtensions`).
 */
export type ImportExtension = 'js' | 'ts';

export const DEFAULT_IMPORT_EXTENSION: ImportExtension = 'js';

export const MANIFEST_FILE_NAME = 'endpoints.gen.ts';

const COMPILED_EXTENSION: Record<string, string> = {
  '.ts': '.js',
  '.mts': '.mjs',
};

function importSpecifier(key: string, importExtension: ImportExtension) {
  const ext = path.extname(key);
  const specifier =
    importExtension === 'js' && COMPILED_EXTENSION[ext]
      ? key.slice(0, -ext.length) + COMPILED_EXTENSION[ext]
      : key;
  return `./${specifier}`;
}

/** The source of an endpoint manifest listing `files` (sorted, relative). */
export function renderManifest(files: readonly string[], importExtension: ImportExtension): string {
  // JSON.stringify quotes keys and specifiers: file names routinely carry
  // `$` (path params), and may carry quotes or backslashes.
  const entries = files.map(
    (key) =>
      `    ${JSON.stringify(key)}: () => import(${JSON.stringify(importSpecifier(key, importExtension))}),`,
  );
  return [
    '// Generated by nestjs-endpoints. Do not edit: the app keeps this file in',
    '// sync while it runs in development, and `npx nestjs-endpoints generate`',
    '// rewrites it on demand.',
    'import { registerEndpointManifest } from "nestjs-endpoints";',
    '',
    'registerEndpointManifest(import.meta.url, {',
    `  importExtension: ${JSON.stringify(importExtension)},`,
    '  files: {',
    ...entries,
    '  },',
    '});',
    '',
  ].join('\n');
}

/**
 * Writes the manifest unless the file already says exactly that — a needless
 * write still restarts watchers. Atomically (temp file, then rename), so a
 * process importing it, or another writing it at the same moment like
 * parallel test workers, never sees half a file. Returns whether it wrote.
 */
export function writeManifest(
  file: string,
  keys: readonly string[],
  importExtension: ImportExtension,
): boolean {
  const content = renderManifest(keys, importExtension);
  if (fs.existsSync(file) && fs.readFileSync(file, 'utf8') === content) {
    return false;
  }
  const temp = path.join(path.dirname(file), `.${path.basename(file)}.${crypto.randomUUID()}.tmp`);
  fs.writeFileSync(temp, content);
  try {
    fs.renameSync(temp, file);
  } catch (error) {
    fs.rmSync(temp, { force: true });
    throw error;
  }
  return true;
}

/**
 * The `importExtension` an existing manifest file declares, so regenerating it
 * keeps the setting. Read from the text — the file is TypeScript and may have
 * been reformatted, so this tolerates either quote style.
 */
export function readImportExtension(file: string): ImportExtension {
  try {
    const match = /importExtension:\s*["'](js|ts)["']/.exec(fs.readFileSync(file, 'utf8'));
    return (match?.[1] as ImportExtension | undefined) ?? DEFAULT_IMPORT_EXTENSION;
  } catch {
    return DEFAULT_IMPORT_EXTENSION;
  }
}

export const DEFAULT_SOURCE_DIR = 'src';

/**
 * Writes `<dir>/endpoints.gen.ts` from the files under `dir`. Without an
 * explicit `importExtension`, an existing manifest's setting is kept.
 */
export function generateManifest(opts: { dir: string; importExtension?: ImportExtension }): {
  file: string;
  keys: string[];
  written: boolean;
} {
  if (!fs.statSync(opts.dir, { throwIfNoEntry: false })?.isDirectory()) {
    throw new Error(`Source directory not found: ${opts.dir}`);
  }
  const file = path.join(opts.dir, MANIFEST_FILE_NAME);
  const keys = scanRoutingFiles(opts.dir);
  const written = writeManifest(file, keys, opts.importExtension ?? readImportExtension(file));
  return { file, keys, written };
}

/** Matches every manifest, wherever the project keeps its sources. */
const MANIFEST_PATTERN = `**/${MANIFEST_FILE_NAME}`;

/**
 * Flags manifests as generated where the project already says so for other
 * files: `.gitattributes` (collapses them in GitHub diffs) always, and
 * `.prettierignore` when the project has one. Idempotent. Returns the files
 * it changed.
 */
export function markGenerated(cwd: string): string[] {
  const changed: string[] = [];
  const append = (name: string, line: string, create: boolean) => {
    const file = path.join(cwd, name);
    const existing = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : undefined;
    if (existing === undefined && !create) {
      return;
    }
    if (existing?.split(/\r?\n/).some((l) => l.trim() === line)) {
      return;
    }
    const separator = existing && !existing.endsWith('\n') ? '\n' : '';
    fs.writeFileSync(file, `${existing ?? ''}${separator}${line}\n`);
    changed.push(file);
  };
  append('.gitattributes', `${MANIFEST_PATTERN} linguist-generated`, true);
  append('.prettierignore', MANIFEST_PATTERN, false);
  return changed;
}
