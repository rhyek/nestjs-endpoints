import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {
  generateManifest,
  markGenerated,
  readImportExtension,
  renderManifest,
  writeManifest,
} from './file';

describe('renderManifest', () => {
  test('js: specifiers carry the compiled extension', () => {
    const out = renderManifest(['a.endpoint.ts', 'b/router.module.mts', 'c.endpoint.js'], 'js');
    expect(out).toContain('importExtension: "js"');
    expect(out).toContain('"a.endpoint.ts": () => import("./a.endpoint.js"),');
    expect(out).toContain('"b/router.module.mts": () => import("./b/router.module.mjs"),');
    expect(out).toContain('"c.endpoint.js": () => import("./c.endpoint.js"),');
  });

  test('ts: specifiers are the files as written', () => {
    const out = renderManifest(['a.endpoint.ts'], 'ts');
    expect(out).toContain('importExtension: "ts"');
    expect(out).toContain('"a.endpoint.ts": () => import("./a.endpoint.ts"),');
  });

  test('quotes file names that need it', () => {
    const out = renderManifest(['it\'s "$id".endpoint.ts'], 'js');
    expect(out).toContain(
      String.raw`"it's \"$id\".endpoint.ts": () => import("./it's \"$id\".endpoint.js"),`,
    );
  });

  test('a manifest with no files is still a valid registration', () => {
    expect(renderManifest([], 'js')).toMatchInlineSnapshot(`
      "// Generated by nestjs-endpoints. Do not edit: the app keeps this file in
      // sync while it runs in development, and \`npx nestjs-endpoints generate\`
      // rewrites it on demand.
      import { registerEndpointManifest } from "nestjs-endpoints";

      registerEndpointManifest(import.meta.url, {
        importExtension: "js",
        files: {
        },
      });
      "
    `);
  });
});

describe('the manifest file', () => {
  let dir: string;
  let file: string;

  beforeEach(() => {
    dir = fs.mkdtempSync(path.join(os.tmpdir(), 'ne-file-'));
    file = path.join(dir, 'endpoints.gen.ts');
  });

  test('writeManifest replaces the file and leaves no temp file behind', () => {
    fs.writeFileSync(file, 'old');
    writeManifest(file, ['a.endpoint.ts'], 'ts');
    expect(fs.readFileSync(file, 'utf8')).toBe(renderManifest(['a.endpoint.ts'], 'ts'));
    expect(fs.readdirSync(dir)).toEqual(['endpoints.gen.ts']);
  });

  test('writeManifest leaves a file that already says the same alone', () => {
    expect(writeManifest(file, ['a.endpoint.ts'], 'js')).toBe(true);
    const before = fs.statSync(file).mtimeMs;
    expect(writeManifest(file, ['a.endpoint.ts'], 'js')).toBe(false);
    expect(fs.statSync(file).mtimeMs).toBe(before);
    expect(writeManifest(file, ['a.endpoint.ts'], 'ts')).toBe(true);
  });

  describe('readImportExtension', () => {
    test('reads what the generator wrote', () => {
      writeManifest(file, [], 'ts');
      expect(readImportExtension(file)).toBe('ts');
    });

    test('survives a formatter switching quotes', () => {
      fs.writeFileSync(
        file,
        "registerEndpointManifest(import.meta.url, { importExtension: 'ts', files: {} });",
      );
      expect(readImportExtension(file)).toBe('ts');
    });

    test('defaults to js for a missing or unrecognized file', () => {
      expect(readImportExtension(file)).toBe('js');
      fs.writeFileSync(file, '// something else');
      expect(readImportExtension(file)).toBe('js');
    });
  });
});

describe('generateManifest and markGenerated', () => {
  let cwd: string;
  let src: string;

  beforeEach(() => {
    cwd = fs.mkdtempSync(path.join(os.tmpdir(), 'ne-gen-'));
    src = path.join(cwd, 'src');
    fs.mkdirSync(path.join(src, 'shop'), { recursive: true });
    fs.writeFileSync(path.join(src, 'shop/stats.endpoint.ts'), '');
  });

  describe('generateManifest', () => {
    test('writes the manifest for the directory', () => {
      const { file, keys, written } = generateManifest({ dir: src });
      expect(file).toBe(path.join(src, 'endpoints.gen.ts'));
      expect(keys).toEqual(['shop/stats.endpoint.ts']);
      expect(written).toBe(true);
      expect(generateManifest({ dir: src }).written).toBe(false);
      expect(fs.readFileSync(file, 'utf8')).toContain('import("./shop/stats.endpoint.js")');
    });

    test('leaves an unchanged manifest untouched, so watchers do not react', () => {
      const { file } = generateManifest({ dir: src });
      const before = fs.statSync(file).mtimeMs;
      expect(generateManifest({ dir: src }).written).toBe(false);
      expect(fs.statSync(file).mtimeMs).toBe(before);
    });

    test('keeps the import extension unless told otherwise', () => {
      generateManifest({ dir: src, importExtension: 'ts' });
      generateManifest({ dir: src });
      expect(readImportExtension(path.join(src, 'endpoints.gen.ts'))).toBe('ts');
      generateManifest({ dir: src, importExtension: 'js' });
      expect(readImportExtension(path.join(src, 'endpoints.gen.ts'))).toBe('js');
    });

    test('a missing directory is an error', () => {
      expect(() => generateManifest({ dir: path.join(cwd, 'nope') })).toThrow(
        /Source directory not found/,
      );
    });
  });

  describe('markGenerated', () => {
    const read = (name: string) => fs.readFileSync(path.join(cwd, name), 'utf8');

    test('creates .gitattributes, and leaves prettier alone when unused', () => {
      expect(markGenerated(cwd)).toEqual([path.join(cwd, '.gitattributes')]);
      expect(read('.gitattributes')).toBe('**/endpoints.gen.ts linguist-generated\n');
      expect(fs.existsSync(path.join(cwd, '.prettierignore'))).toBe(false);
    });

    test('appends to existing files once', () => {
      fs.writeFileSync(path.join(cwd, '.gitattributes'), '* text=auto');
      fs.writeFileSync(path.join(cwd, '.prettierignore'), 'dist\n');
      markGenerated(cwd);
      expect(markGenerated(cwd)).toEqual([]);
      expect(read('.gitattributes')).toBe('* text=auto\n**/endpoints.gen.ts linguist-generated\n');
      expect(read('.prettierignore')).toBe('dist\n**/endpoints.gen.ts\n');
    });
  });
});
